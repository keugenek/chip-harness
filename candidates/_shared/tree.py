"""Shared generator pieces written by the agent in iteration 1 and reused afterwards.

A design is: registered inputs -> partial-product bits dropped into weighted columns ->
Dadda column compression (timing-aware bit selection) -> one carry-propagate adder -> output register.
Everything is emitted as explicit gates so the synthesis tool cannot re-merge the arithmetic.
"""
def clog2(n): return (n - 1).bit_length()

class Net:
    def __init__(self): self.lines = []; self.k = 0
    def wire(self, expr, hint="t"):
        self.k += 1; n = f"{hint}{self.k}"
        self.lines.append(f"  wire {n} = {expr};"); return n

def dadda_targets(maxh):
    d = [2]
    while d[-1] < maxh: d.append(d[-1] * 3 // 2)
    return [x for x in reversed(d) if x < maxh]

def compress(net, cols, width):
    """cols: {weight: [(name, arrival)]}. Returns two rows (lists of names or None) of length `width`."""
    cols = {i: list(cols.get(i, [])) for i in range(width)}
    fa = ha = 0
    for d in dadda_targets(max(len(c) for c in cols.values())):
        incoming = {i: [] for i in range(width + 1)}
        for i in range(width):
            bits = sorted(cols[i], key=lambda b: b[1])      # earliest arrivals are compressed first
            h = len(bits) + len(incoming[i]); out = []
            while h > d:
                while len(bits) < 3 and incoming[i]: bits.append(incoming[i].pop(0))   # rare: borrow a same-stage carry
                if h == d + 1:
                    (x, tx), (y, ty) = bits[0], bits[1]; bits = bits[2:]
                    s = net.wire(f"{x} ^ {y}", "hs"); c = net.wire(f"{x} & {y}", "hc")
                    t = max(tx, ty); out.append((s, t + 1)); incoming[i + 1].append((c, t + 1)); h -= 1; ha += 1
                else:
                    (x, tx), (y, ty), (z, tz) = bits[0], bits[1], bits[2]; bits = bits[3:]
                    p = net.wire(f"{x} ^ {y}", "fp")
                    s = net.wire(f"{p} ^ {z}", "fs"); c = net.wire(f"({x} & {y}) | ({p} & {z})", "fc")
                    t = max(tx, ty); out.append((s, max(t + 1, tz) + 1)); incoming[i + 1].append((c, max(t + 1, tz) + 1))
                    h -= 2; fa += 1
            cols[i] = bits + out + incoming[i]
    r0 = [cols[i][0][0] if len(cols[i]) > 0 else "1'b0" for i in range(width)]
    r1 = [cols[i][1][0] if len(cols[i]) > 1 else "1'b0" for i in range(width)]
    assert all(len(cols[i]) <= 2 for i in range(width))
    return r0, r1, fa, ha

def add_const(cols, k, width):
    for i in range(width):
        if (k >> i) & 1: cols.setdefault(i, []).append(("1'b1", 0))

def module(n, yw, body, wreg_bits, wreg_next, comment, sum_expr="r0 + r1"):
    """wreg_bits: width of the weight-side register; wreg_next: expression stored in it."""
    return f"""// {comment}
// Generated by gen.py for N={n}. Do not edit by hand.
module dot_s8 (
  input  wire              clk,
  input  wire              rst_n,
  input  wire [{n*8-1}:0]  a,
  input  wire [{n*8-1}:0]  w,
  output reg  [{yw-1}:0]   y
);
  reg  [{n*8-1}:0] a_q;
  reg  [{wreg_bits-1}:0] w_q;
  wire [{wreg_bits-1}:0] w_d;
{wreg_next}
{body}
  always @(posedge clk or negedge rst_n)
    if (!rst_n) begin a_q <= 0; w_q <= 0; y <= 0; end
    else begin a_q <= a; w_q <= w_d; y <= {sum_expr}; end
endmodule
"""

def prefix_adder(net, r0, r1, width):
    """Sklansky parallel-prefix adder (log2 depth). Added in iteration 2 after timing analysis
    showed the tool-inferred final adder rippling through ~12 carry stages."""
    g = [net.wire(f"{r0[i]} & {r1[i]}", "g") for i in range(width)]
    p = [net.wire(f"{r0[i]} ^ {r1[i]}", "p") for i in range(width)]
    G, P = list(g), list(p); d = 1
    while d < width:
        nG, nP = list(G), list(P)
        for i in range(width):
            if (i // d) % 2 == 1:                              # upper half of each 2d block
                j = (i // d) * d - 1                           # top of the lower half
                nG[i] = net.wire(f"{G[i]} | ({P[i]} & {G[j]})", "G")
                nP[i] = net.wire(f"{P[i]} & {P[j]}", "P")
        G, P = nG, nP; d *= 2
    return [p[0]] + [net.wire(f"{p[i]} ^ {G[i-1]}", "s") for i in range(1, width)]

def finish(net, cols, n, yw, wreg_bits, wreg_next, comment, adder="tool"):
    r0, r1, fa, ha = compress(net, cols, yw)
    sum_expr = "r0 + r1"
    if adder == "prefix":
        sbits = prefix_adder(net, r0, r1, yw)
        sum_expr = "{" + ", ".join(reversed(sbits)) + "}"
    body = "\n".join(net.lines)
    body += f"\n  wire [{yw-1}:0] r0 = {{{', '.join(reversed(r0))}}};"
    body += f"\n  wire [{yw-1}:0] r1 = {{{', '.join(reversed(r1))}}};"
    return module(n, yw, body, wreg_bits, wreg_next, comment + f" [{fa} full adders, {ha} half adders, final adder: {adder}]", sum_expr)

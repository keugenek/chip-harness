#!/usr/bin/env python3
"""Generate zero-delay functional Verilog cell models from Liberty 'function' attributes.

Why: the foundry Verilog models rely on $setuphold delayed signals that Icarus cannot drive,
and UDP-based gate simulation of ~10k cells is too slow for an inner loop. Models derived from
the same .lib that synthesis and STA use keep a single source of truth for cell behaviour.
Usage: lib2v.py <in.lib> <out.v>
"""
import re, sys

def blocks(text, pattern):
    for m in re.finditer(pattern, text):
        i = m.end(); d = 1
        while d:
            c = text[i]
            d += (c == '{') - (c == '}'); i += 1
        yield m.group(1), text[m.end():i]

def conv(f):
    f = f.replace('!', '~').replace('*', '&').replace('+', '|')
    f = re.sub(r"(\w+|\))'", r"~\1", f)
    return re.sub(r'(\w|\))\s+(?=[\w(~])', r'\1 & ', f)      # juxtaposition means AND

def main(src, dst):
    lib = open(src).read()
    v = ["// Functional cell models generated from the Liberty 'function' attributes of",
         f"// {src.split('/')[-1]} (the same file used for synthesis and timing).",
         "// Zero-delay; for fast gate-level simulation. Generated by harness/lib2v.py.", ""]
    for name, body in sorted(blocks(lib, r'\n\s*cell\s*\(\s*(\w+)\s*\)\s*\{')):
        pins = []
        for pn, pb in blocks(body, r'\bpin\s*\(\s*"?(\w+)"?\s*\)\s*\{'):
            d = re.search(r'direction\s*:\s*"?(\w+)"?', pb); f = re.search(r'\bfunction\s*:\s*"([^"]*)"', pb)
            pins.append((pn, d.group(1) if d else '?', f.group(1) if f else None))
        outs = [p for p in pins if p[1] == 'output']; ins = [p for p in pins if p[1] == 'input']
        if (re.search(r'\b(ff|latch)\s*\(', body) or 'clock_gating' in body or 'three_state' in body
                or not outs or any(o[2] is None for o in outs)):
            continue                                            # sequential / tristate / physical-only cells
        v.append(f"module {name} ({', '.join([p[0] for p in ins] + [p[0] for p in outs])});")
        v += [f"  input {p[0]};" for p in ins]
        for p in outs: v += [f"  output {p[0]};", f"  assign {p[0]} = {conv(p[2])};"]
        v.append("endmodule\n")
    # D flip-flops with active-low async reset (ff group: clear "!RESET_B", clocked_on "CLK", next_state "D")
    for nm, qn in (("sg13g2_dfrbpq_1", 0), ("sg13g2_dfrbpq_2", 0), ("sg13g2_dfrbp_1", 1), ("sg13g2_dfrbp_2", 1)):
        v.append(f"module {nm} (CLK, D, RESET_B, Q{', Q_N' if qn else ''});")
        v.append("  input CLK, D, RESET_B; output reg Q;" + (" output Q_N; assign Q_N = ~Q;" if qn else ""))
        v.append("  always @(posedge CLK or negedge RESET_B) if (!RESET_B) Q <= 1'b0; else Q <= D;")
        v.append("endmodule\n")
    open(dst, "w").write("\n".join(v))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
